CREATE TABLE IF NOT EXISTS handover (
    handover_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_id VARCHAR(20) NOT NULL REFERENCES patient(patient_id),
    encounter_id INT NOT NULL REFERENCES encounter(encounter_id),
    tier VARCHAR(80) NOT NULL,
    actionable BOOLEAN NOT NULL,
    urgency VARCHAR(30) NOT NULL,
    contract JSONB NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS ix_handover_patient ON handover(patient_id, created_at DESC);

