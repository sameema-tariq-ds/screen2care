-- Immutable result of the versioned rules engine. Never update an assessment.
CREATE TABLE IF NOT EXISTS assessments (
    assessment_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_id VARCHAR(20) NOT NULL REFERENCES patient(patient_id),
    encounter_id INT NOT NULL REFERENCES encounter(encounter_id),
    tier VARCHAR(80) NOT NULL,
    actionable BOOLEAN NOT NULL,
    urgency VARCHAR(30) NOT NULL,
    reasons JSONB NOT NULL DEFAULT '[]'::jsonb,
    missing JSONB NOT NULL DEFAULT '[]'::jsonb,
    rules_version VARCHAR(40) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS ix_assessments_encounter ON assessments(encounter_id, created_at DESC);

CREATE OR REPLACE FUNCTION reject_assessment_mutation() RETURNS trigger AS $$
BEGIN
    RAISE EXCEPTION 'assessments are immutable';
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS assessments_immutable ON assessments;
CREATE TRIGGER assessments_immutable
BEFORE UPDATE OR DELETE ON assessments
FOR EACH ROW EXECUTE FUNCTION reject_assessment_mutation();

