-- =====================================================================
-- Screening-to-Care Loop | PostgreSQL schema
-- Docker runs this automatically on the first start of the database.
-- =====================================================================

CREATE EXTENSION IF NOT EXISTS vector;   -- pgvector, for the LLM / RAG layer later

-- ---------------------------------------------------------------------
-- 1. STAFF
-- ---------------------------------------------------------------------
CREATE TABLE staff (
    staff_id   INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name  VARCHAR(150) NOT NULL,
    role       VARCHAR(30)  NOT NULL
        CHECK (role IN ('Admin','Radiologist','Clinician','Pathologist','Navigator',
                        'SchedulingManager','LabDirector','TumorBoard','CMO','RadiologyHead')),
    is_active  BOOLEAN NOT NULL DEFAULT TRUE
);

-- ---------------------------------------------------------------------
-- 2. PATIENT + RISK DATA (inputs for Steps 1, 2 and 4)
-- ---------------------------------------------------------------------
CREATE TABLE patient (
    patient_id     VARCHAR(20) PRIMARY KEY,          -- e.g. BC-HP-001
    full_name      VARCHAR(150) NOT NULL,
    date_of_birth  DATE NOT NULL,
    national_id    VARCHAR(30),                      -- encrypt in production
    phone          VARCHAR(30),
    created_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
    created_by     INT REFERENCES staff(staff_id)
);
CREATE UNIQUE INDEX ux_patient_national_id ON patient(national_id) WHERE national_id IS NOT NULL;

CREATE TABLE patient_risk_profile (
    patient_id              VARCHAR(20) PRIMARY KEY REFERENCES patient(patient_id),
    menarche_age            SMALLINT,
    menopausal_status       VARCHAR(20) CHECK (menopausal_status IN ('Premenopausal','Perimenopausal','Postmenopausal')),
    menopause_age           SMALLINT,
    parity                  SMALLINT,
    age_first_birth         SMALLINT,
    ocp_use                 VARCHAR(10) CHECK (ocp_use IN ('Never','Past','Current')),
    hrt_use                 BOOLEAN,
    hrt_duration_years      NUMERIC(4,1),
    height_cm               NUMERIC(5,1),
    weight_kg               NUMERIC(5,1),
    bmi                     NUMERIC(4,1) GENERATED ALWAYS AS
                                (ROUND(weight_kg / ((height_cm / 100.0) * (height_cm / 100.0)), 1)) STORED,
    genetic_status          VARCHAR(20) NOT NULL DEFAULT 'Never tested'
        CHECK (genetic_status IN ('Positive','Negative','Unknown','Pending','Never tested')),
    genetic_mutation        VARCHAR(30),             -- e.g. BRCA1
    chest_radiation_age     SMALLINT,                -- Step 1: radiation between ages 10-30
    chest_radiation_note    VARCHAR(200),
    high_risk_lesion        VARCHAR(4) CHECK (high_risk_lesion IN ('ADH','ALH','LCIS')),
    lifetime_risk_pct       NUMERIC(5,2),            -- Step 1: >= 20%
    risk_model              VARCHAR(30),             -- e.g. Tyrer-Cuzick
    risk_data_status        VARCHAR(10) NOT NULL DEFAULT 'Pending'
        CHECK (risk_data_status IN ('Complete','Pending')),
    genetics_referral_flag  BOOLEAN NOT NULL DEFAULT FALSE,
    updated_at              TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE family_history (
    family_history_id  INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_id         VARCHAR(20) NOT NULL REFERENCES patient(patient_id),
    relation           VARCHAR(30) NOT NULL,         -- Mother, Sister, Maternal Aunt, Unspecified
    relation_degree    SMALLINT CHECK (relation_degree IN (1,2,3)),
    cancer_type        VARCHAR(20) NOT NULL CHECK (cancer_type IN ('Breast','Ovarian','Pancreatic','Prostate','Other')),
    age_at_diagnosis   SMALLINT,
    known_genetic_mutations VARCHAR(8) NOT NULL DEFAULT 'Unknown'
      CHECK (known_genetic_mutations IN ('BRCA1','BRCA2','Negative','Unknown'))
);

CREATE TABLE prior_breast_procedure (
    procedure_id        INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_id          VARCHAR(20) NOT NULL REFERENCES patient(patient_id),
    procedure_type      VARCHAR(20) NOT NULL CHECK (procedure_type IN ('CystAspiration','Biopsy','Surgery','Other')),
    laterality          CHAR(1) CHECK (laterality IN ('L','R','B')),
    procedure_year      SMALLINT,
    result_summary      VARCHAR(200),
    is_high_risk_lesion BOOLEAN NOT NULL DEFAULT FALSE
);

CREATE TABLE comorbidity (
    comorbidity_id    INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_id        VARCHAR(20) NOT NULL REFERENCES patient(patient_id),
    description       VARCHAR(200) NOT NULL,
    is_severe_active  BOOLEAN NOT NULL DEFAULT FALSE,   -- Step 4 input
    recorded_at       DATE NOT NULL
);

-- ---------------------------------------------------------------------
-- 3. ENCOUNTERS (every visit = new row; nothing is overwritten)
-- ---------------------------------------------------------------------
CREATE TABLE encounter (
    encounter_id           INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_id             VARCHAR(20) NOT NULL REFERENCES patient(patient_id),
    encounter_date         TIMESTAMPTZ NOT NULL,
    encounter_type         VARCHAR(25) NOT NULL
        CHECK (encounter_type IN ('Screening','Diagnostic','HighRiskSurveillance','Recall','FollowUp')),
    is_symptomatic         BOOLEAN NOT NULL DEFAULT FALSE,   -- Step 0 gate
    chief_complaint        VARCHAR(200),
    symptom_duration_days  SMALLINT,
    clinician_id           INT REFERENCES staff(staff_id),
    entered_by             INT REFERENCES staff(staff_id),
    created_at             TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX ix_encounter_patient ON encounter(patient_id, encounter_date);

CREATE TABLE clinical_breast_exam (
    cbe_id                  INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    encounter_id            INT NOT NULL REFERENCES encounter(encounter_id),
    laterality              CHAR(1) NOT NULL CHECK (laterality IN ('L','R')),
    inspection_normal       BOOLEAN NOT NULL,
    inspection_finding      VARCHAR(100),
    mass_present            BOOLEAN NOT NULL,
    mass_size_mm            SMALLINT,
    mass_mobility           VARCHAR(6) CHECK (mass_mobility IN ('Mobile','Fixed')),
    axillary_node_palpable  BOOLEAN NOT NULL,
    is_abnormal             BOOLEAN GENERATED ALWAYS AS
                                (NOT inspection_normal OR mass_present OR axillary_node_palpable) STORED,
    CONSTRAINT uq_cbe_encounter_side UNIQUE (encounter_id, laterality)
);

-- Doctor notes: versioned, with a release-to-patient step
CREATE TABLE clinical_note (
    note_id                 INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    encounter_id            INT NOT NULL REFERENCES encounter(encounter_id),
    author_id               INT NOT NULL REFERENCES staff(staff_id),
    note_type               VARCHAR(15) NOT NULL
        CHECK (note_type IN ('Clinical','Radiology','Pathology','TumorBoard','Navigator','Disposition')),
    note_text               TEXT NOT NULL,
    version_no              INT NOT NULL DEFAULT 1,
    supersedes_note_id      INT REFERENCES clinical_note(note_id),
    is_released_to_patient  BOOLEAN NOT NULL DEFAULT FALSE,
    released_at             TIMESTAMPTZ,
    released_by             INT REFERENCES staff(staff_id),
    created_at              TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- ---------------------------------------------------------------------
-- 4. IMAGING (input for the Step 3 BI-RADS matrix)
-- ---------------------------------------------------------------------
CREATE TABLE imaging_result (
    imaging_id          INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    encounter_id        INT NOT NULL REFERENCES encounter(encounter_id),
    patient_id          VARCHAR(20) NOT NULL REFERENCES patient(patient_id),
    modality            VARCHAR(12) NOT NULL CHECK (modality IN ('Mammogram','DBT','Ultrasound','ABUS','MRI')),
    laterality          CHAR(1) NOT NULL CHECK (laterality IN ('L','R','B')),
    birads_category     SMALLINT NOT NULL CHECK (birads_category BETWEEN 0 AND 6),
    birads_subcategory  VARCHAR(2) CHECK (birads_subcategory IN ('4A','4B','4C')),
    density             CHAR(1) CHECK (density IN ('A','B','C','D')),   -- mammography only
    result_released_at  TIMESTAMPTZ NOT NULL,        -- S1 and S2 clocks start here
    radiologist_id      INT REFERENCES staff(staff_id),
    report_text         TEXT
);
CREATE INDEX ix_imaging_patient ON imaging_result(patient_id, result_released_at);

-- ---------------------------------------------------------------------
-- 5. CARE EPISODE (one loop per abnormal result) + its events
-- ---------------------------------------------------------------------
CREATE TABLE care_episode (
    episode_id          INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_id          VARCHAR(20) NOT NULL REFERENCES patient(patient_id),
    trigger_imaging_id  INT NOT NULL REFERENCES imaging_result(imaging_id),
    opened_at           TIMESTAMPTZ NOT NULL,
    status              VARCHAR(25) NOT NULL DEFAULT 'Open'
        CHECK (status IN ('Open','Paused','Closed-TreatmentStarted','Closed-Benign',
                          'Closed-Declined','Closed-Transferred','Closed-Deceased')),
    pause_reason        VARCHAR(200),
    closed_at           TIMESTAMPTZ,
    closure_note        VARCHAR(400)
);
CREATE UNIQUE INDEX ux_episode_one_active ON care_episode(patient_id) WHERE status IN ('Open','Paused');

CREATE TABLE patient_contact (                      -- S1
    contact_id       INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    episode_id       INT NOT NULL REFERENCES care_episode(episode_id),
    channel          VARCHAR(8) NOT NULL CHECK (channel IN ('SMS','Phone','Email','InPerson')),
    attempted_at     TIMESTAMPTZ NOT NULL,
    acknowledged_at  TIMESTAMPTZ,
    outcome          VARCHAR(12) CHECK (outcome IN ('NoAnswer','Reached','WrongNumber','Declined')),
    performed_by     INT REFERENCES staff(staff_id)
);

CREATE TABLE biopsy (                               -- S2
    biopsy_id      INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    episode_id     INT NOT NULL REFERENCES care_episode(episode_id),
    biopsy_type    VARCHAR(12) NOT NULL CHECK (biopsy_type IN ('US-Core','Stereotactic','MRI-Guided','Surgical')),
    laterality     CHAR(1) CHECK (laterality IN ('L','R')),
    ordered_at     TIMESTAMPTZ NOT NULL,
    booked_at      TIMESTAMPTZ,
    scheduled_for  TIMESTAMPTZ,
    performed_at   TIMESTAMPTZ,
    status         VARCHAR(10) NOT NULL DEFAULT 'Ordered'
        CHECK (status IN ('Ordered','Booked','Performed','NoShow','Cancelled','Declined')),
    no_show_count  SMALLINT NOT NULL DEFAULT 0
);

CREATE TABLE pathology_result (                     -- S3
    pathology_id    INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    biopsy_id       INT NOT NULL UNIQUE REFERENCES biopsy(biopsy_id),
    reported_at     TIMESTAMPTZ NOT NULL,
    diagnosis       VARCHAR(15) NOT NULL CHECK (diagnosis IN ('Benign','HighRiskLesion','Malignant','NonDiagnostic')),
    histology       VARCHAR(100),
    er_status       VARCHAR(8) CHECK (er_status IN ('Positive','Negative')),
    pr_status       VARCHAR(8) CHECK (pr_status IN ('Positive','Negative')),
    her2_status     VARCHAR(9) CHECK (her2_status IN ('Positive','Negative','Equivocal')),
    ki67_pct        NUMERIC(5,2),
    concordance     VARCHAR(11) NOT NULL DEFAULT 'Pending'
        CHECK (concordance IN ('Concordant','Discordant','Pending')),
    pathologist_id  INT REFERENCES staff(staff_id),
    report_text     TEXT
);

CREATE TABLE referral (                             -- S4 (+ genetics referrals)
    referral_id     INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_id      VARCHAR(20) NOT NULL REFERENCES patient(patient_id),
    episode_id      INT REFERENCES care_episode(episode_id),
    specialty       VARCHAR(20) NOT NULL
        CHECK (specialty IN ('SurgicalOncology','MedicalOncology','RadiationOncology','TumorBoard','Genetics')),
    created_at      TIMESTAMPTZ NOT NULL,
    assigned_to_id  INT REFERENCES staff(staff_id),
    assigned_at     TIMESTAMPTZ,
    status          VARCHAR(10) NOT NULL DEFAULT 'Pending'
        CHECK (status IN ('Pending','Assigned','Seen','Cancelled'))
);

CREATE TABLE treatment (                            -- S5
    treatment_id    INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    episode_id      INT NOT NULL REFERENCES care_episode(episode_id),
    treatment_type  VARCHAR(16) NOT NULL
        CHECK (treatment_type IN ('Surgery','NeoadjuvantChemo','Chemotherapy','Radiation','Endocrine','Other')),
    ordered_at      TIMESTAMPTZ,
    started_at      TIMESTAMPTZ                      -- S5 completion event
);

-- ---------------------------------------------------------------------
-- 6. SLA (rules stored as data)
-- ---------------------------------------------------------------------
CREATE TABLE sla_definition (
    section                  SMALLINT PRIMARY KEY CHECK (section BETWEEN 1 AND 5),
    name                     VARCHAR(40) NOT NULL,
    target_hours             INT NOT NULL,
    clock_start_event        VARCHAR(30) NOT NULL,
    completion_event         VARCHAR(30) NOT NULL,
    escalation1_role         VARCHAR(30) NOT NULL,
    escalation2_role         VARCHAR(30),
    escalation2_after_hours  INT
);

CREATE TABLE sla_task (
    sla_task_id        INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    episode_id         INT NOT NULL REFERENCES care_episode(episode_id),
    section            SMALLINT NOT NULL REFERENCES sla_definition(section),
    started_at         TIMESTAMPTZ NOT NULL,
    due_at             TIMESTAMPTZ NOT NULL,
    completed_at       TIMESTAMPTZ,
    status             VARCHAR(10) NOT NULL DEFAULT 'Running'
        CHECK (status IN ('Running','Met','Breached','Paused','Cancelled')),
    escalation_level   SMALLINT NOT NULL DEFAULT 0,
    last_escalated_at  TIMESTAMPTZ,
    CONSTRAINT uq_sla_task_episode_section UNIQUE (episode_id, section)
);
CREATE INDEX ix_sla_task_due ON sla_task(status, due_at);

-- ---------------------------------------------------------------------
-- 7. LANE ASSIGNMENT (rules engine output, with history)
-- ---------------------------------------------------------------------
CREATE TABLE lane_assignment (
    lane_assignment_id  INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_id          VARCHAR(20) NOT NULL REFERENCES patient(patient_id),
    source_imaging_id   INT REFERENCES imaging_result(imaging_id),
    lane                VARCHAR(25) NOT NULL
        CHECK (lane IN ('DataPending','Diagnostic','HighRisk-MRIOnly','HighRisk-DBT+MRI',
                        'HighRisk-DBT+ConsiderMRI','WellnessHold','RoutineScreening',
                        'DenseSupplemental','ShortInterval6M','RecallBirads0',
                        'UrgentWorkup','Treatment','SymptomaticCareOnly')),
    assigned_at         TIMESTAMPTZ NOT NULL DEFAULT now(),
    next_due_date       DATE,
    reason              VARCHAR(400) NOT NULL,
    assigned_by         VARCHAR(9) NOT NULL CHECK (assigned_by IN ('Engine','Clinician')),
    clinician_id        INT REFERENCES staff(staff_id),
    override_reason     VARCHAR(400),
    is_current          BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT ck_lane_override_needs_reason CHECK (assigned_by = 'Engine' OR override_reason IS NOT NULL)
);
CREATE UNIQUE INDEX ux_lane_one_current ON lane_assignment(patient_id) WHERE is_current;

-- ---------------------------------------------------------------------
-- 8. AUDIT / EVENT LOG
-- ---------------------------------------------------------------------
CREATE TABLE event_log (
    event_id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_id  VARCHAR(20) NOT NULL REFERENCES patient(patient_id),
    episode_id  INT REFERENCES care_episode(episode_id),
    event_type  VARCHAR(40) NOT NULL,                -- ResultReleased, BiopsyPerformed, LaneChanged ...
    event_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
    actor_id    INT REFERENCES staff(staff_id),
    details     JSONB
);
CREATE INDEX ix_event_log_patient ON event_log(patient_id, event_at);

-- ---------------------------------------------------------------------
-- 9. VIEWS FOR THE DASHBOARDS
-- ---------------------------------------------------------------------
CREATE VIEW vw_sla_status AS
SELECT  t.sla_task_id, e.patient_id, p.full_name, t.section, d.name AS section_name,
        t.started_at, t.due_at, t.completed_at, t.escalation_level,
        CASE
            WHEN t.status IN ('Paused','Cancelled')                      THEN t.status
            WHEN t.completed_at IS NOT NULL AND t.completed_at <= t.due_at THEN 'Met'
            WHEN t.completed_at IS NOT NULL                              THEN 'MetLate'
            WHEN now() > t.due_at                                        THEN 'Breached'
            ELSE 'Running'
        END AS live_status,
        FLOOR(EXTRACT(EPOCH FROM (t.due_at - now())) / 3600)::INT AS hours_remaining
FROM sla_task t
JOIN care_episode   e ON e.episode_id = t.episode_id
JOIN patient        p ON p.patient_id = e.patient_id
JOIN sla_definition d ON d.section    = t.section;

CREATE VIEW vw_data_quality_flags AS
SELECT e.patient_id, e.encounter_id, 'AbnormalCBE_RecordedAsAsymptomatic' AS flag
FROM encounter e
WHERE NOT e.is_symptomatic
  AND EXISTS (SELECT 1 FROM clinical_breast_exam c WHERE c.encounter_id = e.encounter_id AND c.is_abnormal)
UNION ALL
SELECT r.patient_id, NULL, 'RiskDataPending'
FROM patient_risk_profile r
WHERE r.risk_data_status = 'Pending'
UNION ALL
SELECT f.patient_id, NULL, 'FamilyHistoryRelationUnspecified'
FROM family_history f
WHERE f.relation = 'Unspecified';

-- Patient dashboard: only notes a clinician has released
CREATE VIEW vw_patient_released_notes AS
SELECT e.patient_id, e.encounter_date, n.note_type, n.note_text, n.released_at
FROM clinical_note n
JOIN encounter e ON e.encounter_id = n.encounter_id
WHERE n.is_released_to_patient;
