CREATE TABLE IF NOT EXISTS plan_items (
    plan_item_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_id VARCHAR(20) NOT NULL REFERENCES patient(patient_id),
    encounter_id INT NOT NULL REFERENCES encounter(encounter_id),
    plan_option VARCHAR(80) NOT NULL,
    due_date DATE,
    status VARCHAR(20) NOT NULL DEFAULT 'Planned'
        CHECK (status IN ('Planned', 'Completed', 'Cancelled')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS ix_plan_items_due ON plan_items(status, due_date);

